def square_law_id_vt(vg, vd, vt):
    """用指定阈值 V_T 的 Square-law 电流（与 constants.square_law_id 同一
    公式，但阈值可指定——用于"用提取 V_T 对照"，故公开）。"""
    vg = np.asarray(vg, dtype=float)
    ov = vg - vt
    vdsat = np.maximum(ov, 0.0)
    id_lin = C.MU_N * C.COX * (C.W_CH / C.L_CH) * (ov * vd - 0.5 * vd ** 2)
    id_sat = 0.5 * C.MU_N * C.COX * (C.W_CH / C.L_CH) * vdsat ** 2
    return np.where(ov <= 0.0, 0.0, np.where(vd < vdsat, id_lin, id_sat))


